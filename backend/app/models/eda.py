from pydantic import BaseModel, Field, model_validator
from typing import Dict, Any, List
from app.models.artifact import CollectedArtifact

class EDARequest(BaseModel):
    dataset_artifact_id: str = Field(..., description="The ID of the dataset to analyze")
    analysis_type: str = Field(..., description="The type of analysis to perform")
    parameters: Dict[str, Any] = Field(default_factory=dict, description="Parameters for the analysis")
    requested_outputs: List[str] = Field(default_factory=list, description="Specific outputs requested")

class EDAResult(BaseModel):
    summary: str = Field(..., description="Narrative summary of the analysis")
    metrics: Dict[str, Any] = Field(default_factory=dict, description="Key metrics computed")
    findings: List[str] = Field(default_factory=list, description="Key insights discovered")
    warnings: List[str] = Field(default_factory=list, description="Any warnings or caveats")
    artifacts: List[CollectedArtifact] = Field(default_factory=list, description="New artifacts generated by the EDA")
    execution_metadata: Dict[str, Any] = Field(default_factory=dict, description="Metadata about the execution (time taken, mode used)")
    errors: List[str] = Field(default_factory=list, description="Any errors encountered during analysis")
